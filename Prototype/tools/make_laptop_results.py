def cp(k, n, a=0.05):
    lo = 0.0 if k == 0 else beta.ppf(a / 2, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(1 - a / 2, k + 1, n - k)
    return f"{100 * k / n:.1f} % [{100 * lo:.1f}, {100 * hi:.1f}] (n={n})"


def pct(rate_ci):
    return f"{rate_ci:.1f}"


def boot_wer(per_utt, seed=0, B=2000):
    x = np.array(per_utt, float)  # [words, word_errs, chars, char_errs]
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(x), (B, len(x)))
    w = x[idx, 1].sum(1) / x[idx, 0].sum(1) * 100
    c = x[idx, 3].sum(1) / x[idx, 2].sum(1) * 100
    return np.percentile(w, [2.5, 97.5]), np.percentile(c, [2.5, 97.5])


